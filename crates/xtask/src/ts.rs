fn notification_policy() -> NotificationPolicy {
    let enabled = NotificationKindPolicy {
        agent_blocked: true,
        approval_required: true,
        turn_completed: true,
        session_finished: true,
        error: true,
        system: true,
    };
    let mut providers = BTreeMap::new();
    providers.insert(
        "codex".to_owned(),
        NotificationKindPolicy {
            turn_completed: false,
            ..enabled.clone()
        },
    );
    providers.insert(
        "future-agent".to_owned(),
        NotificationKindPolicy {
            system: false,
            ..enabled.clone()
        },
    );
    NotificationPolicy {
        attention_dedupe_window_secs: 30,
        attention_debounce_secs: 5,
        enabled,
        providers,
        retention: protocol::NotificationRetentionPolicy::default(),
    }
}

fn fixture<T>(file_name: &'static str, value: &T) -> Result<NamedFixture, XtaskError>
where
    T: Serialize,
{
    Ok(NamedFixture {
        file_name,
        value: json_value(value)?,
    })
}

fn json_value<T>(value: &T) -> Result<Value, XtaskError>
where
    T: Serialize,
{
    serde_json::to_value(value).map_err(XtaskError::Json)
}

