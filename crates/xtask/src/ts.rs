#[derive(Clone, Debug, Eq, PartialEq)]
pub(crate) struct TsSummary {
    pub(crate) generated_files: usize,
    pub(crate) fixture_files: usize,
}

#[derive(Clone, Debug, Eq, PartialEq)]
struct TsPaths {
    generated_dir: PathBuf,
    fixture_dir: PathBuf,
}

#[derive(Clone, Debug, Eq, PartialEq)]
struct NamedFixture {
    file_name: &'static str,
    value: Value,
}

#[derive(Clone, Debug)]
struct FixtureValues {
    session_full: SessionInfo,
    session_minimal: SessionInfo,
    error_with_recover: ProtocolError,
    error_without_recover: ProtocolError,
    session_filter: SessionListFilter,
    notification: NotificationRecord,
}

pub(crate) fn generate(root: &Path) -> Result<TsSummary, XtaskError> {
    let paths = TsPaths {
        generated_dir: root.join(GENERATED_DIR),
        fixture_dir: root.join(FIXTURE_DIR),
    };
    regenerate(root, &paths)
}

pub(crate) fn check(root: &Path) -> Result<(), XtaskError> {
    let temp_root = temp_check_root();
    let paths = TsPaths {
        generated_dir: temp_root.join("generated"),
        fixture_dir: temp_root.join("fixtures"),
    };

    let result = (|| {
        regenerate(root, &paths)?;
        compare_output_dirs(
            &root.join(GENERATED_DIR),
            &paths.generated_dir,
            GENERATED_DIR,
        )?;
        compare_output_dirs(&root.join(FIXTURE_DIR), &paths.fixture_dir, FIXTURE_DIR)?;
        Ok(())
    })();

    if temp_root.exists() {
        let _ = fs::remove_dir_all(&temp_root);
    }

    result
}

fn regenerate(root: &Path, paths: &TsPaths) -> Result<TsSummary, XtaskError> {
    remove_dir_all_if_exists(&paths.generated_dir)?;
    remove_dir_all_if_exists(&paths.fixture_dir)?;
    create_dir_all(&paths.generated_dir)?;
    create_dir_all(&paths.fixture_dir)?;

    let export_dir = absolute_path(&paths.generated_dir)?;
    run_ts_rs_export(root, &export_dir)?;
    rewrite_ts_rs_headers(&paths.generated_dir)?;

    let type_names = exported_type_names(&paths.generated_dir)?;
    emit_index(&paths.generated_dir, &type_names)?;
    emit_methods(&paths.generated_dir)?;
    emit_constants(&paths.generated_dir)?;
    emit_events(&paths.generated_dir)?;
    emit_fixtures(&paths.fixture_dir)?;

    Ok(TsSummary {
        generated_files: count_files(&paths.generated_dir)?,
        fixture_files: count_files(&paths.fixture_dir)?,
    })
}

fn run_ts_rs_export(root: &Path, export_dir: &Path) -> Result<(), XtaskError> {
    let status = Command::new("cargo")
        .current_dir(root)
        .args([
            "test",
            "-p",
            "pohunek-protocol",
            "--features",
            "ts",
            EXPORT_BINDINGS_TEST,
        ])
        .env("TS_RS_EXPORT_DIR", export_dir)
        .status()
        .map_err(|source| XtaskError::Io {
            path: PathBuf::from("cargo"),
            source,
        })?;

    if status.success() {
        Ok(())
    } else {
        Err(XtaskError::Usage(format!(
            "ts-rs export failed with {status}; fix the protocol bindings and rerun `cargo xtask ts generate`"
        )))
    }
}

fn rewrite_ts_rs_headers(dir: &Path) -> Result<(), XtaskError> {
    for path in ts_files(dir)? {
        let content = read_to_string(&path)?;
        let body = strip_existing_generated_header(&content);
        write_generated_file(&path, body)?;
    }
    Ok(())
}

fn strip_existing_generated_header(content: &str) -> &str {
    if let Some(body) = content.strip_prefix(GENERATED_HEADER) {
        body
    } else if content.starts_with("// This file was generated") {
        content
            .split_once('\n')
            .map_or("", |(_, body)| body.trim_start_matches('\n'))
    } else {
        content
    }
}

fn emit_index(dir: &Path, type_names: &[String]) -> Result<(), XtaskError> {
    let mut body = String::new();
    for type_name in type_names {
        writeln!(
            body,
            "export type {{ {type_name} }} from \"./{type_name}\";"
        )
        .expect("writing to a String cannot fail");
    }
    body.push_str(
        "\nexport type JsonValue =\n  | null\n  | boolean\n  | number\n  | string\n  | JsonValue[]\n  | { [key: string]: JsonValue };\n",
    );
    write_generated_file(&dir.join("index.ts"), &body)
}

fn emit_methods(dir: &Path) -> Result<(), XtaskError> {
    let mut specs = method::METHOD_SPECS.to_vec();
    specs.sort_by_key(|spec| spec.name);

    let imports = method_imports(&specs);
    let mut body = String::new();
    push_type_import(&mut body, &imports);
    body.push_str("export interface Methods {\n");
    for spec in specs {
        writeln!(
            body,
            "  \"{}\": {{ params: {}; output: {} }};",
            spec.name, spec.params_ts, spec.output_ts
        )
        .expect("writing to a String cannot fail");
    }
    body.push_str("}\n");

    write_generated_file(&dir.join("methods.ts"), &body)
}

fn emit_constants(dir: &Path) -> Result<(), XtaskError> {
    let mut event_specs = event::EVENT_SPECS.to_vec();
    event_specs.sort_by_key(|spec| spec.name);

    let mut body = String::from("import type { AttachHeader } from \"./index\";\n\n");
    writeln!(
        body,
        "export const PROTOCOL_VERSION = {} as const;",
        PROTOCOL_VERSION.get()
    )
    .expect("writing to a String cannot fail");
    writeln!(
        body,
        "export const MIN_PROTOCOL_VERSION = {} as const;",
        MIN_PROTOCOL_VERSION.get()
    )
    .expect("writing to a String cannot fail");
    writeln!(
        body,
        "export const SUPPORTED_PROTOCOL_VERSIONS = {{ minimum: {}, maximum: {} }} as const;",
        SUPPORTED_PROTOCOL_VERSIONS.minimum().get(),
        SUPPORTED_PROTOCOL_VERSIONS.maximum().get()
    )
    .expect("writing to a String cannot fail");
    writeln!(
        body,
        "export const MAX_CONTROL_LINE_BYTES = {MAX_CONTROL_LINE_BYTES} as const;"
    )
    .expect("writing to a String cannot fail");
    writeln!(
        body,
        "export const MAX_RUNTIME_ID_BYTES = {MAX_RUNTIME_ID_BYTES} as const;"
    )
    .expect("writing to a String cannot fail");
    writeln!(
        body,
        "export const MAX_SESSION_INPUT_BYTES = {MAX_SESSION_INPUT_BYTES} as const;"
    )
    .expect("writing to a String cannot fail");
    writeln!(
        body,
        "export const MAX_SESSION_OUTPUT_BYTES = {MAX_SESSION_OUTPUT_BYTES} as const;"
    )
    .expect("writing to a String cannot fail");
    writeln!(
        body,
        "export const MAX_SESSION_WAIT_MS = {MAX_SESSION_WAIT_MS} as const;\n"
    )
    .expect("writing to a String cannot fail");

    let mut constant_names = Vec::new();
    for spec in &event_specs {
        let constant_name = event_constant_name(spec.name);
        writeln!(
            body,
            "export const {constant_name} = \"{}\" as const;",
            spec.name
        )
        .expect("writing to a String cannot fail");
        constant_names.push(constant_name);
    }

    body.push_str("\nexport const EVENT_NAMES = [\n");
    for constant_name in &constant_names {
        writeln!(body, "  {constant_name},").expect("writing to a String cannot fail");
    }
    body.push_str("] as const;\n\n");
    body.push_str("export type EventName = (typeof EVENT_NAMES)[number];\n");
    body.push_str("export type AttachPrelude = AttachHeader;\n");
    body.push_str("export const ATTACH_PRELUDE_FIELDS = [\"attach\"] as const;\n");

    write_generated_file(&dir.join("constants.ts"), &body)
}

fn emit_events(dir: &Path) -> Result<(), XtaskError> {
    let mut event_specs = event::EVENT_SPECS.to_vec();
    event_specs.sort_by_key(|spec| spec.name);

    let mut imports = BTreeSet::new();
    imports.insert("ProtocolVersion".to_owned());
    for spec in &event_specs {
        imports.insert(spec.payload_ts.to_owned());
    }

    let mut body = String::new();
    push_type_import(&mut body, &imports);
    body.push_str("export type ProtocolEvent =\n");
    for spec in event_specs {
        writeln!(
            body,
            "  | ({{ v: ProtocolVersion; event: \"{}\"; id?: string }} & {})",
            spec.name, spec.payload_ts
        )
        .expect("writing to a String cannot fail");
    }
    body.push_str(";\n");

    write_generated_file(&dir.join("events.ts"), &body)
}

fn emit_fixtures(dir: &Path) -> Result<(), XtaskError> {
    for fixture in fixtures()? {
        write_json_file(&dir.join(fixture.file_name), &fixture.value)?;
    }
    Ok(())
}

