//! TypeScript protocol binding generation.
//!
//! Derived wire types are exported by `ts-rs`; the non-derivable SDK scaffolding
//! (method map, event union, constants, and JSON fixtures) is emitted here from
//! protocol metadata so it cannot drift from the Rust wire contract.
//!
//! Optionality policy: protocol fields that serde omits with
//! `skip_serializing_if = "Option::is_none"` carry `#[ts(optional)]` on the Rust
//! field, so TypeScript sees `field?: T`. `Option` fields without that serde
//! omission remain explicit `T | null`. This generator never post-processes
//! optionality; `ts-rs` serde compatibility stays the source of truth.

