    fn pi_spec() -> ExistenceSpec {
        ExistenceSpec {
            root_env: Some("AGENT_CONFIG_DIR".to_owned()),
            root_home: Some(".agent".to_owned()),
            dir: Some("sessions".to_owned()),
            file_name: Some("_{reference}.jsonl".to_owned()),
            name_match: Some(NameMatch::EndsWith),
            max_depth: Some(1),
            ..spec(ExistenceCheckKind::File)
        }
    }

    fn existence(spec: ExistenceSpec) -> ReferenceExistence {
        ReferenceExistence::try_from(spec).expect("valid declaration")
    }

    fn reference(value: &str) -> SessionRef {
        SessionRef::id(value).expect("id reference")
    }

    fn env_of(vars: Vec<(&'static str, OsString)>) -> impl Fn(&str) -> Option<OsString> {
        move |name| {
            vars.iter()
                .find(|(key, _)| *key == name)
                .map(|(_, value)| value.clone())
        }
    }

