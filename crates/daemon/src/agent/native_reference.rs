    fn symlinks_never_lead_the_scan_outside_the_store() {
        let outside = tempdir().expect("outside dir");
        fs::write(outside.path().join("t_abc.jsonl"), "{}").expect("outside file");
        let store = store_with("proj", "t_other.jsonl");
        let sessions = store.root.join("sessions");
        std::os::unix::fs::symlink(outside.path(), sessions.join("link")).expect("dir symlink");
        std::os::unix::fs::symlink(
            outside.path().join("t_abc.jsonl"),
            sessions.join("proj").join("t_abc.jsonl"),
        )
        .expect("file symlink");
        let env = env_of(vec![(
            "AGENT_CONFIG_DIR",
            store.root.clone().into_os_string(),
        )]);
        assert_eq!(
            existence(pi_spec()).verify(&reference("abc"), &env),
            Err(ReferenceCheckFailure::Missing),
            "neither a linked directory nor a linked file counts"
        );
    }

    #[cfg(unix)]
    #[test]
    fn a_directory_swapped_for_a_symlink_after_discovery_is_not_entered() {
        let outside = tempdir().expect("outside dir");
        fs::write(outside.path().join("t_abc.jsonl"), "{}").expect("outside file");
        let store = store_with("proj", "t_other.jsonl");
        let ReferenceExistence::File(check) = existence(pi_spec()) else {
            panic!("a file check");
        };
        let root = fs::canonicalize(&store.root).expect("canonical root");
        let target = outside.path().to_path_buf();
        let mut swapped = false;
        let outcome = check.scan_store(&root, "_abc.jsonl", &mut |directory| {
            // The scan has typed `proj` as a directory and is about to open
            // it: replace it with a link to a directory that holds a match.
            fs::remove_dir_all(directory).expect("remove discovered directory");
            std::os::unix::fs::symlink(&target, directory).expect("swap in a symlink");
            swapped = true;
        });
        assert!(swapped, "the hook ran between discovery and traversal");
        assert!(
            matches!(outcome, Err(ReferenceCheckFailure::StoreChanged)),
            "a match behind the swapped-in link must not be found"
        );
    }

    /// Runs the Pi-shaped scan over `<root>/sessions` with `hook` between
    /// discovery and open.
    fn scan_sessions(
        root: &Path,
        wanted: &str,
        hook: &mut dyn FnMut(&Path),
    ) -> Result<(), ReferenceCheckFailure> {
        let ReferenceExistence::File(check) = existence(pi_spec()) else {
            panic!("a file check");
        };
        let root = fs::canonicalize(root).expect("canonical root");
        check.scan_store(&root, wanted, hook).map(|_| ())
    }

    #[test]
    fn a_directory_that_vanishes_after_discovery_does_not_end_the_scan() {
        let store = store_with("first", "t_other.jsonl");
        let sessions = store.root.join("sessions");
        fs::create_dir_all(sessions.join("second")).expect("second dir");
        fs::write(sessions.join("second").join("t_other.jsonl"), "{}").expect("file");
        let mut removed = Vec::new();
        let outcome = scan_sessions(&store.root, "_abc.jsonl", &mut |directory| {
            if !removed.is_empty() {
                return;
            }
            // The directory opened first disappears, and the conversation
            // appears in its sibling, which the scan has not opened yet. The
            // order the directories are listed in does not matter.
            let sibling = if directory.ends_with("first") {
                "second"
            } else {
                "first"
            };
            fs::write(sessions.join(sibling).join("t_abc.jsonl"), "{}").expect("match");
            fs::remove_dir_all(directory).expect("remove discovered directory");
            removed.push(directory.to_path_buf());
        });
        assert_eq!(removed.len(), 1);
        assert_eq!(
            outcome,
            Ok(()),
            "the sibling holding the match is still searched"
        );
    }

    #[test]
    fn a_scan_whose_only_candidate_vanishes_reports_missing() {
        let store = store_with("gone", "t_abc.jsonl");
        let outcome = scan_sessions(&store.root, "_abc.jsonl", &mut |directory| {
            fs::remove_dir_all(directory).expect("remove discovered directory");
        });
        assert_eq!(outcome, Err(ReferenceCheckFailure::Missing));
    }

