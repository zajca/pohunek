    #[test]
    fn file_check_validates_every_field() {
        ReferenceExistence::try_from(pi_spec()).expect("the baseline is valid");

        let long_path = "a/b/c/d/e/f/g/h/i".to_owned();
        let cases: Vec<(&str, ExistenceSpec)> = vec![
            (
                "root_env",
                pi_spec_with(|spec| {
                    spec.root_env = None;
                    spec.root_home = None;
                }),
            ),
            (
                "root_env",
                pi_spec_with(|s| s.root_env = Some("POHUNEK_HOME".to_owned())),
            ),
            (
                "root_env",
                pi_spec_with(|s| s.root_env = Some("lower".to_owned())),
            ),
            (
                "root_home",
                pi_spec_with(|s| s.root_home = Some("/etc".to_owned())),
            ),
            ("dir", pi_spec_with(|s| s.dir = Some("a/../b".to_owned()))),
            ("dir", pi_spec_with(|s| s.dir = Some("*".to_owned()))),
            ("dir", pi_spec_with(|s| s.dir = Some(long_path))),
            ("file_name", pi_spec_with(|s| s.file_name = None)),
            (
                "file_name",
                pi_spec_with(|s| s.file_name = Some("plain.jsonl".to_owned())),
            ),
            (
                "file_name",
                pi_spec_with(|s| s.file_name = Some("{reference}{reference}".to_owned())),
            ),
            (
                "file_name",
                pi_spec_with(|s| s.file_name = Some("../{reference}".to_owned())),
            ),
            (
                "file_name",
                pi_spec_with(|s| s.file_name = Some("*{reference}".to_owned())),
            ),
            ("name_match", pi_spec_with(|s| s.name_match = None)),
            ("max_depth", pi_spec_with(|s| s.max_depth = None)),
            (
                "max_depth",
                pi_spec_with(|s| s.max_depth = Some(MAX_EXISTENCE_DEPTH + 1)),
            ),
        ];
        for (field, case) in cases {
            let error = ReferenceExistence::try_from(case.clone())
                .expect_err(&format!("{field} must be rejected: {case:?}"));
            assert_eq!(error.field(), field, "{case:?}");
        }
    }

    #[test]
    fn declarations_roundtrip_and_reject_corruption() {
        for declared in [ReferenceExistence::Unchecked, existence(pi_spec())] {
            let encoded = serde_json::to_string(&declared).expect("encode");
            let decoded: ReferenceExistence = serde_json::from_str(&encoded).expect("decode");
            assert_eq!(decoded, declared);
        }
        let traversal = r#"{"check":"file","root_home":"..","file_name":"{reference}","name_match":"exact","max_depth":0}"#;
        serde_json::from_str::<ReferenceExistence>(traversal)
            .expect_err("a traversal root must not decode");
        let unknown = r#"{"check":"none","extra":1}"#;
        serde_json::from_str::<ReferenceExistence>(unknown)
            .expect_err("an unknown field must not decode");
    }

    struct Store {
        _dir: tempfile::TempDir,
        root: PathBuf,
    }

    /// `<root>/sessions/<project>/<stamp>_<id>.jsonl` below a temp root.
    fn store_with(project: &str, file: &str) -> Store {
        let dir = tempdir().expect("temp dir");
        let root = dir.path().to_path_buf();
        let project_dir = root.join("sessions").join(project);
        fs::create_dir_all(&project_dir).expect("project dir");
        fs::write(project_dir.join(file), "{}").expect("session file");
        Store { _dir: dir, root }
    }

    #[test]
    fn a_timestamped_file_below_the_declared_directory_is_found() {
        let store = store_with("proj", "2026-10-04T10-00-00Z_abc-123.jsonl");
        let check = existence(pi_spec());
        let env = env_of(vec![(
            "AGENT_CONFIG_DIR",
            store.root.clone().into_os_string(),
        )]);
        assert_eq!(check.verify(&reference("abc-123"), &env), Ok(()));
        assert_eq!(
            check.verify(&reference("abc-124"), &env),
            Err(ReferenceCheckFailure::Missing)
        );
        assert_eq!(
            check.verify(&reference("c-123"), &env),
            Err(ReferenceCheckFailure::Missing),
            "an ends_with match needs the declared `_` boundary"
        );
    }

