//! The installed layout a release consumer run executes from, and the checks
//! that bind what ran to the bytes it was given.
//!
//! The three release binaries are copied into
//! `<prefix>/libexec/pohunek/<version>/`, the directory the service installer
//! uses. The daemon finds its worker and its trust anchor beside its own
//! executable there. Every digest is taken from file contents. On Linux, a running
//! image is hashed through `/proc/<pid>/exe`, which reads the inode that was
//! executed even if the path was replaced afterwards. On macOS, the executable path
//! is read via the host inspector and verified against the installed bytes.

// Rust guideline compliant 2026-10-13

use std::fmt;
use std::fs;
use std::os::unix::fs::PermissionsExt as _;
use std::path::{Path, PathBuf};
use std::process::Command;

use pohunek_test_support::fs::write_file;
use sha2::{Digest as _, Sha256};

use super::release_bounded::{run as run_bounded, PROBE_TIMEOUT};
use super::release_env::BINARIES;

/// Mode of an installed executable.
const EXECUTABLE_MODE: u32 = 0o755;

/// Mode of the installed trust anchor, which holds public keys only.
const ANCHOR_MODE: u32 = 0o644;

/// Mode of the directories of the layout, the installer's public mode. The
/// daemon refuses an anchor whose directory chain group or others can write.
const DIRECTORY_MODE: u32 = 0o755;

/// Subdirectory of the prefix that holds one directory per installed version.
const LIBEXEC: &str = "libexec/pohunek";

/// Name of the staging directory the binaries are copied into before the
/// version is known.
const STAGE: &str = ".stage";

/// Prefix of the name of every pohunek binary.
const POHUNEK_NAME_PREFIX: &str = "pohunek";

/// Size of the read buffer used while hashing.
const HASH_BUFFER_BYTES: usize = 64 * 1024;

/// Where the trust anchor beside the daemon comes from.
pub(crate) enum AnchorSource<'a> {
    /// No anchor file; the daemon reports an absent anchor.
    None,
    /// The archive's own anchor file, copied byte for byte.
    File(&'a Path),
    /// Bytes generated by the harness (row mode).
    Bytes(&'a [u8]),
}

/// Why the layout cannot be trusted.
#[derive(Debug)]
pub(crate) enum LayoutError {
    Io {
        what: String,
        source: std::io::Error,
    },
    /// The three binaries do not agree on one release version.
    Version { detail: String },
    /// A file's bytes differ from the bytes recorded when it was installed, or
    /// from the source it was copied from.
    Changed {
        file: String,
        expected: String,
        actual: String,
        against: &'static str,
    },
    /// A running process does not execute a file of the layout.
    OutsideLayout {
        pid: u32,
        executable: PathBuf,
        layout: PathBuf,
    },
    /// A running pohunek process executes a file of the layout whose bytes
    /// differ from the installed ones, or one that is not a pohunek binary.
    ImageMismatch {
        pid: u32,
        executable: PathBuf,
        detail: String,
    },
}

impl fmt::Display for LayoutError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Io { what, source } => write!(f, "{what}: {source}"),
            Self::Version { detail } => write!(f, "release version mismatch: {detail}"),
            Self::Changed {
                file,
                expected,
                actual,
                against,
            } => write!(
                f,
                "{file} is not byte-identical to {against}: expected sha256 {expected}, found {actual}"
            ),
            Self::OutsideLayout {
                pid,
                executable,
                layout,
            } => write!(
                f,
                "process {pid} runs {} which is outside the layout {}",
                executable.display(),
                layout.display()
            ),
            Self::ImageMismatch {
                pid,
                executable,
                detail,
            } => write!(
                f,
                "process {pid} runs {}: {detail}",
                executable.display()
            ),
        }
    }
}

impl std::error::Error for LayoutError {}

fn io<T>(what: impl Into<String>, result: std::io::Result<T>) -> Result<T, LayoutError> {
    result.map_err(|source| LayoutError::Io {
        what: what.into(),
        source,
    })
}

/// Maps a [`pohunek_platform::process::Error`] to [`LayoutError::Io`].
#[cfg(target_os = "macos")]
fn inspect<T>(
    what: impl Into<String>,
    result: Result<T, pohunek_platform::process::Error>,
) -> Result<T, LayoutError> {
    result.map_err(|error| LayoutError::Io {
        what: what.into(),
        source: std::io::Error::other(error),
    })
}

/// SHA-256 of everything `reader` yields, as 64 lowercase hex characters.
pub(crate) fn sha256_reader(mut reader: impl std::io::Read) -> std::io::Result<String> {
    let mut hasher = Sha256::new();
    let mut buffer = vec![0_u8; HASH_BUFFER_BYTES];
    loop {
        let read = reader.read(&mut buffer)?;
        if read == 0 {
            break;
        }
        hasher.update(&buffer[..read]);
    }
    Ok(hasher
        .finalize()
        .iter()
        .fold(String::with_capacity(64), |mut hex, byte| {
            use std::fmt::Write as _;
            let _ = write!(hex, "{byte:02x}");
            hex
        }))
}

/// SHA-256 of the file at `path`.
pub(crate) fn sha256_file(path: &Path) -> std::io::Result<String> {
    sha256_reader(fs::File::open(path)?)
}

/// One file installed into the layout.
#[derive(Debug)]
struct Installed {
    name: String,
    /// The file the bytes were copied from; `None` for generated bytes.
    source: Option<PathBuf>,
    path: PathBuf,
    digest: String,
}

/// The installed directory of one run.
#[derive(Debug)]
pub(crate) struct Layout {
    pub(crate) version: String,
    pub(crate) dir: PathBuf,
    files: Vec<Installed>,
}

impl Layout {
    /// Copies the three binaries of `bin_dir` (and the anchor) below `prefix`
    /// and returns the layout named after the release version they report.
    ///
    /// # Errors
    ///
    /// Fails when a file cannot be copied, when `pohunekd --version` and
    /// `pohunek --version` do not report one version, or when the copy differs
    /// from its source.
    pub(crate) fn install(
        bin_dir: &Path,
        prefix: &Path,
        anchor: &AnchorSource<'_>,
    ) -> Result<Self, LayoutError> {
        let libexec = prefix.join(LIBEXEC);
        io(
            format!("create {}", libexec.display()),
            fs::create_dir_all(&libexec),
        )?;
        let directories = [
            prefix.to_path_buf(),
            prefix.join("libexec"),
            libexec.clone(),
        ];
        for dir in &directories {
            io(
                format!("mode of {}", dir.display()),
                fs::set_permissions(dir, fs::Permissions::from_mode(DIRECTORY_MODE)),
            )?;
        }
        let stage = libexec.join(STAGE);
        io(
            format!("create {}", stage.display()),
            fs::create_dir_all(&stage),
        )?;
        // The creation mode is filtered by the umask; set it explicitly so the
        // daemon's anchor policy sees the installer's mode whatever the umask.
        io(
            format!("mode of {}", stage.display()),
            fs::set_permissions(&stage, fs::Permissions::from_mode(DIRECTORY_MODE)),
        )?;

        let mut staged = Vec::new();
        for name in BINARIES {
            staged.push(copy_file(
                name,
                &Content::Copy(bin_dir.join(name)),
                &stage,
                EXECUTABLE_MODE,
            )?);
        }
        match anchor {
            AnchorSource::None => {}
            AnchorSource::File(path) => staged.push(copy_file(
                package::ANCHOR_FILE_NAME,
                &Content::Copy((*path).to_path_buf()),
                &stage,
                ANCHOR_MODE,
            )?),
            AnchorSource::Bytes(bytes) => staged.push(copy_file(
                package::ANCHOR_FILE_NAME,
                &Content::Bytes(bytes),
                &stage,
                ANCHOR_MODE,
            )?),
        }

        let version = release_version(&stage)?;
        let dir = libexec.join(&version);
        io(
            format!("move {} to {}", stage.display(), dir.display()),
            fs::rename(&stage, &dir),
        )?;
        let files = staged
            .into_iter()
            .map(|file| Installed {
                path: dir.join(&file.name),
                ..file
            })
            .collect();
        let layout = Self {
            version,
            dir,
            files,
        };
        layout.verify_files()?;
        Ok(layout)
    }

    fn file(&self, name: &str) -> &Installed {
        self.files
            .iter()
            .find(|file| file.name == name)
            .unwrap_or_else(|| panic!("{name} is not part of the layout"))
    }

    /// Path of the installed binary `name`.
    pub(crate) fn path(&self, name: &str) -> &Path {
        &self.file(name).path
    }

    /// SHA-256 of the installed binary `name`, as recorded at install time.
    pub(crate) fn digest(&self, name: &str) -> &str {
        &self.file(name).digest
    }

    /// Whether a process runs a pohunek binary, judged by what it executes
    /// rather than by the name it reports.
    ///
    /// A process qualifies when its command name or its executable's file name
    /// starts with `pohunek`, or when its executable is byte-identical to a
    /// binary of this layout under any name. `image` hashes the executable
    /// only when the names do not already decide; it yields `None` only for a
    /// process that has exited, and fails for a live one whose bytes cannot be
    /// read, so an unreadable copy never passes as a foreign binary.
    ///
    /// # Errors
    ///
    /// Returns the error of `image`.
    fn runs_a_pohunek_binary(
        &self,
        command: &str,
        executable: &Path,
        image: impl FnOnce() -> Result<Option<String>, LayoutError>,
    ) -> Result<bool, LayoutError> {
        let named = |name: &str| name.starts_with(POHUNEK_NAME_PREFIX);
        if named(command)
            || executable
                .file_name()
                .and_then(|name| name.to_str())
                .is_some_and(named)
        {
            return Ok(true);
        }
        Ok(image()?
            .is_some_and(|digest| BINARIES.iter().any(|name| self.file(name).digest == digest)))
    }

    /// Re-hashes every installed file and its source.
    ///
    /// # Errors
    ///
    /// Fails naming the first file whose bytes differ from the recorded digest
    /// or from the source it was copied from.
    pub(crate) fn verify_files(&self) -> Result<(), LayoutError> {
        for file in &self.files {
            let installed = io(
                format!("hash {}", file.path.display()),
                sha256_file(&file.path),
            )?;
            if installed != file.digest {
                return Err(LayoutError::Changed {
                    file: file.path.display().to_string(),
                    expected: file.digest.clone(),
                    actual: installed,
                    against: "the bytes recorded at install time",
                });
            }
            if let Some(source) = &file.source {
                let origin = io(format!("hash {}", source.display()), sha256_file(source))?;
                if origin != file.digest {
                    return Err(LayoutError::Changed {
                        file: source.display().to_string(),
                        expected: file.digest.clone(),
                        actual: origin,
                        against: "the copy that runs",
                    });
                }
            }
        }
        Ok(())
    }

    /// Checks that process `pid` executes the layout file `name` and that the
    /// image it executes has the installed bytes.
    ///
    /// # Errors
    ///
    /// Fails when `/proc/<pid>/exe` is not that file, or when the executed
    /// inode hashes differently from the recorded digest.
    #[cfg(target_os = "linux")]
    pub(crate) fn verify_process(&self, pid: u32, name: &str) -> Result<(), LayoutError> {
        let file = self.file(name);
        let executable = io(
            format!("read /proc/{pid}/exe"),
            fs::read_link(format!("/proc/{pid}/exe")),
        )?;
        if executable != file.path {
            return Err(LayoutError::OutsideLayout {
                pid,
                executable,
                layout: self.dir.clone(),
            });
        }
        let image = io(
            format!("hash the image of process {pid}"),
            sha256_file(Path::new(&format!("/proc/{pid}/exe"))),
        )?;
        if image != file.digest {
            return Err(LayoutError::Changed {
                file: format!("the running image of {name} (process {pid})"),
                expected: file.digest.clone(),
                actual: image,
                against: "the installed file",
            });
        }
        Ok(())
    }

    /// Checks that process `pid` executes the layout file `name` and that the
    /// file's current bytes match the recorded digest.
    ///
    /// On macOS, the executable path is read via the host inspector and canonicalized
    /// for comparison. Both the path and the bytes are instantaneous snapshots, and
    /// Darwin offers no handle to the executed image, so the check binds the executable
    /// path and that file's current bytes at observation time; they may race with a
    /// concurrent `exec`.
    ///
    /// # Errors
    ///
    /// Fails when the executable path does not match the layout, when the file's
    /// current bytes differ from the recorded digest, or when the process has exited.
    #[cfg(target_os = "macos")]
    pub(crate) fn verify_process(&self, pid: u32, name: &str) -> Result<(), LayoutError> {
        use pohunek_platform::process::{HostInspector, ProcessInspector as _};

        let file = self.file(name);
        let inspector = HostInspector::new();
        let canonical_dir = io(
            "canonicalize the layout directory",
            fs::canonicalize(&self.dir),
        )?;
        let canonical_layout_path = io("canonicalize layout path", fs::canonicalize(&file.path))?;
        let Some(executable) = inspect(
            format!("read executable of process {pid}"),
            inspector.executable(pid),
        )?
        else {
            return Err(LayoutError::Io {
                what: format!("process {pid} exited"),
                source: std::io::Error::new(
                    std::io::ErrorKind::NotFound,
                    "process no longer exists",
                ),
            });
        };
        let canonical_executable = io(
            "canonicalize executable path",
            fs::canonicalize(&executable),
        )?;
        if canonical_executable != canonical_layout_path {
            return Err(LayoutError::OutsideLayout {
                pid,
                executable: canonical_executable,
                layout: canonical_dir,
            });
        }
        let image = io(
            format!("hash the executable of process {pid}"),
            sha256_file(&canonical_executable),
        )?;
        if image != file.digest {
            return Err(LayoutError::Changed {
                file: format!("the running image of {name} (process {pid})"),
                expected: file.digest.clone(),
                actual: image,
                against: "the installed file",
            });
        }
        Ok(())
    }

    /// Every pohunek process that belongs to the environment rooted at `scope`
    /// (its environment holds a value below `scope`), as `(pid, binary name)`.
    ///
    /// # Errors
    ///
    /// Fails for a process that runs a pohunek binary (see
    /// [`Self::runs_a_pohunek_binary`]) and does not execute a byte-identical
    /// binary of this layout at its installed path.
    #[cfg(target_os = "linux")]
    pub(crate) fn pohunek_processes(
        &self,
        scope: &Path,
    ) -> Result<Vec<(u32, String)>, LayoutError> {
        let mut found = Vec::new();
        let Ok(processes) = fs::read_dir("/proc") else {
            return Ok(found);
        };
        let own = std::process::id();
        for entry in processes.flatten() {
            let Some(pid) = entry
                .file_name()
                .to_str()
                .and_then(|name| name.parse::<u32>().ok())
            else {
                continue;
            };
            if pid == own || !belongs_to(&entry.path(), scope) {
                continue;
            }
            let command = fs::read_to_string(entry.path().join("comm")).unwrap_or_default();
            let executable = match fs::read_link(entry.path().join("exe")) {
                Ok(executable) => executable,
                Err(_) if process_ended(&entry.path()) => continue,
                Err(source) => {
                    return Err(LayoutError::Io {
                        what: format!("read the executable of live process {pid}"),
                        source,
                    });
                }
            };
            // The running image is hashed through /proc/<pid>/exe, the inode
            // that was executed, whatever its path now holds. It stays readable
            // after an unlink, so a failure is an exit only once the process
            // has ended.
            let image = || match sha256_file(&entry.path().join("exe")) {
                Ok(digest) => Ok(Some(digest)),
                Err(_) if process_ended(&entry.path()) => Ok(None),
                Err(source) => Err(LayoutError::Io {
                    what: format!("hash the image of live process {pid}"),
                    source,
                }),
            };
            if !self.runs_a_pohunek_binary(command.trim(), &executable, image)? {
                continue;
            }
            let Some(name) = BINARIES.iter().find(|name| self.path(name) == executable) else {
                return Err(if executable.starts_with(&self.dir) {
                    LayoutError::ImageMismatch {
                        pid,
                        executable,
                        detail: "not one of the three release binaries".to_owned(),
                    }
                } else {
                    LayoutError::OutsideLayout {
                        pid,
                        executable,
                        layout: self.dir.clone(),
                    }
                });
            };
            self.verify_process(pid, name)?;
            found.push((pid, (*name).to_owned()));
        }
        Ok(found)
    }

    /// Every pohunek process that belongs to the environment rooted at `scope`,
    /// as `(pid, binary name)`.
    ///
    /// Only processes inside the scope are checked. A process belongs when its
    /// executable path or working directory lies below the canonicalized `scope`.
    /// The platform inspector exposes only the allowlisted ownership markers of
    /// another process's environment, so membership is decided by executable and
    /// working directory.
    ///
    /// # Errors
    ///
    /// Fails for a process that belongs to the scope, runs a pohunek binary (see
    /// [`Self::runs_a_pohunek_binary`]), and does not execute a byte-identical
    /// binary of this layout. Fails closed on error.
    #[cfg(target_os = "macos")]
    pub(crate) fn pohunek_processes(
        &self,
        scope: &Path,
    ) -> Result<Vec<(u32, String)>, LayoutError> {
        use pohunek_platform::process::{HostInspector, ProcessInspector as _};

        let mut found = Vec::new();
        let inspector = HostInspector::new();
        let processes = inspect(
            "inspect same-user processes",
            inspector.same_user_processes(),
        )?;
        let own = std::process::id();
        let canonical_scope = io("canonicalize scope", fs::canonicalize(scope))?;
        let canonical_dir = io(
            "canonicalize the layout directory",
            fs::canonicalize(&self.dir),
        )?;

        // Pre-compute canonical paths for the layout binaries.
        let layout_binaries = BINARIES
            .iter()
            .map(|name| {
                io(
                    format!("canonicalize layout path {name}"),
                    fs::canonicalize(self.path(name)),
                )
                .map(|path| (*name, path))
            })
            .collect::<Result<Vec<_>, _>>()?;

        let below_root = |path: &Path| -> bool {
            fs::canonicalize(path).is_ok_and(|canonical| canonical.starts_with(&canonical_scope))
        };

        for fact in processes {
            if fact.pid == own {
                continue;
            }

            // Ok(None) means the process exited during the scan.
            let executable = match inspector.executable(fact.pid) {
                Ok(Some(executable)) => executable,
                Ok(None) => continue,
                // An unreadable executable fails the scan only for a process
                // that may belong to the scope or reports a pohunek name; any
                // other process is unrelated whatever it executes.
                Err(error)
                    if fact.comm.starts_with(POHUNEK_NAME_PREFIX)
                        || inspector.cwd(fact.pid).is_ok_and(|cwd| below_root(&cwd)) =>
                {
                    // A process that ended after the failed read is skipped
                    // like any other exit.
                    if !inspect(
                        format!("check if process {} is running", fact.pid),
                        inspector.is_running(fact.identity()),
                    )? {
                        continue;
                    }
                    return Err(LayoutError::Io {
                        what: format!("read executable of process {}", fact.pid),
                        source: std::io::Error::other(error),
                    });
                }
                Err(_) => continue,
            };

            // Check membership BEFORE processing the executable so unrelated processes
            // outside the scope cannot fail the run.
            // The RAW executable path (proc_pidpath returns canonical) or cwd below scope.
            let belongs = executable.starts_with(&canonical_scope)
                || inspector.cwd(fact.pid).is_ok_and(|cwd| below_root(&cwd));

            if !belongs {
                continue;
            }
            // Darwin offers no handle to the executed image, so the bytes are
            // those the executable path holds at observation time. A path that
            // cannot be hashed is an exit only once the process is gone.
            let image = || match sha256_file(&executable) {
                Ok(digest) => Ok(Some(digest)),
                Err(source) => {
                    if inspect(
                        format!("check if process {} is running", fact.pid),
                        inspector.is_running(fact.identity()),
                    )? {
                        Err(LayoutError::Io {
                            what: format!("hash the executable of live process {}", fact.pid),
                            source,
                        })
                    } else {
                        Ok(None)
                    }
                }
            };
            if !self.runs_a_pohunek_binary(&fact.comm, &executable, image)? {
                continue;
            }

            // Only for members: canonicalize and check the executable.
            let canonical_exe = match fs::canonicalize(&executable) {
                Ok(path) => path,
                Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
                    // Process executable is no longer available. Check if the process is still running.
                    match inspect(
                        format!("check if process {pid} is running", pid = fact.pid),
                        inspector.is_running(fact.identity()),
                    ) {
                        Ok(false) => {
                            // Process has exited; skip it.
                            continue;
                        }
                        Ok(true) => {
                            // Process is alive but its executable path no longer resolves.
                            return Err(LayoutError::Io {
                                what: format!(
                                    "the executable of live process {} no longer resolves",
                                    fact.pid
                                ),
                                source: e,
                            });
                        }
                        Err(err) => return Err(err),
                    }
                }
                Err(source) => {
                    return Err(LayoutError::Io {
                        what: format!("canonicalize executable of process {}", fact.pid),
                        source,
                    })
                }
            };

            let Some((name, _)) = layout_binaries
                .iter()
                .find(|(_, path)| path == &canonical_exe)
            else {
                return Err(if canonical_exe.starts_with(&canonical_dir) {
                    LayoutError::ImageMismatch {
                        pid: fact.pid,
                        executable: canonical_exe,
                        detail: "not one of the three release binaries".to_owned(),
                    }
                } else {
                    LayoutError::OutsideLayout {
                        pid: fact.pid,
                        executable: canonical_exe,
                        layout: canonical_dir.clone(),
                    }
                });
            };

            self.verify_process(fact.pid, name)?;
            found.push((fact.pid, (*name).to_owned()));
        }

        Ok(found)
    }
}

/// Whether the process of `directory` (a `/proc/<pid>` entry) has ended: its
/// entry is gone, or it is a zombie or dead task whose image can no longer be
/// read although the entry remains until its parent reaps it. A `stat` that
/// cannot be read while the entry exists proves no exit.
#[cfg(target_os = "linux")]
fn process_ended(directory: &Path) -> bool {
    let Ok(stat) = fs::read_to_string(directory.join("stat")) else {
        return !directory.exists();
    };
    // The state follows the parenthesised command name, which may itself hold
    // spaces or parentheses.
    stat.rsplit_once(')')
        .and_then(|(_, rest)| rest.split_whitespace().next())
        .is_some_and(|state| matches!(state, "Z" | "X" | "x"))
}

/// Whether a value of the process environment of `directory` (a `/proc/<pid>`
/// entry) lies below `scope`.
#[cfg(target_os = "linux")]
fn belongs_to(directory: &Path, scope: &Path) -> bool {
    use std::os::unix::ffi::OsStrExt as _;

    fs::read(directory.join("environ")).is_ok_and(|bytes| {
        bytes
            .split(|byte| *byte == 0)
            .filter_map(|entry| {
                let separator = entry.iter().position(|byte| *byte == b'=')?;
                Some(&entry[separator + 1..])
            })
            .any(|value| Path::new(std::ffi::OsStr::from_bytes(value)).starts_with(scope))
    })
}

/// What an installed file is made of.
enum Content<'a> {
    /// The bytes of an existing file.
    Copy(PathBuf),
    /// Bytes generated by the harness.
    Bytes(&'a [u8]),
}

/// Writes `content` to `dir/name` and records its digest.
fn copy_file(
    name: &str,
    content: &Content<'_>,
    dir: &Path,
    mode: u32,
) -> Result<Installed, LayoutError> {
    let path = dir.join(name);
    // The file is written by a child process: a write descriptor held by this
    // process could leak into a sibling thread's child and make the later
    // exec of the copy fail with ETXTBSY.
    let source = match content {
        Content::Copy(source) => {
            let bytes = io(format!("read {}", source.display()), fs::read(source))?;
            io(
                format!("copy {} to {}", source.display(), path.display()),
                write_file(&path, bytes),
            )?;
            Some(source.clone())
        }
        Content::Bytes(bytes) => {
            io(
                format!("write {}", path.display()),
                write_file(&path, bytes),
            )?;
            None
        }
    };
    io(
        format!("mode of {}", path.display()),
        fs::set_permissions(&path, fs::Permissions::from_mode(mode)),
    )?;
    let digest = io(format!("hash {}", path.display()), sha256_file(&path))?;
    Ok(Installed {
        name: name.to_owned(),
        source,
        path,
        digest,
    })
}

/// The release version the three staged binaries all report.
fn release_version(stage: &Path) -> Result<String, LayoutError> {
    let report = |name: &str| -> Result<String, LayoutError> {
        let mut command = Command::new(stage.join(name));
        command.arg("--version").env_clear();
        let output = run_bounded(command, &format!("{name} --version"), PROBE_TIMEOUT)
            .map_err(|detail| LayoutError::Version { detail })?;
        let text = String::from_utf8_lossy(&output.stdout).into_owned();
        let mut words = text.split_whitespace();
        match (output.status.success(), words.next(), words.next()) {
            (true, Some(program), Some(version)) if program == name => Ok(version.to_owned()),
            _ => Err(LayoutError::Version {
                detail: format!("`{name} --version` printed {text:?}"),
            }),
        }
    };
    let daemon = report("pohunekd")?;
    let cli = report("pohunek")?;
    let worker = report("pohunek-sessiond")?;
    if daemon != cli || daemon != worker {
        return Err(LayoutError::Version {
            detail: format!(
                "pohunekd is {daemon}, pohunek is {cli} and pohunek-sessiond is {worker}; \
                 a release directory holds one version"
            ),
        });
    }
    Ok(daemon)
}
